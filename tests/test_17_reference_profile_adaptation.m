%TEST_17_REFERENCE_PROFILE_ADAPTATION Validate reusable target-profile mapping.

thisFile = mfilename('fullpath');
projectRoot = fileparts(fileparts(thisFile));
addpath(genpath(projectRoot));

makeProfile = @(f0, centroid) struct( ...
    'status', 'ok', ...
    'f0Median', f0, ...
    'f0Cv', 0.08, ...
    'voicedRatio', 0.90, ...
    'voicedRatioOfSpeech', 0.92, ...
    'confidenceMean', 0.88, ...
    'pitchRangeSemitones', 6.0, ...
    'spectralCentroidMedian', centroid, ...
    'energyModulationRateHz', 3.2, ...
    'dynamicRangeDb', 9.0, ...
    'formant1Median', NaN, ...
    'formant2Median', NaN);

sourceLow = makeProfile(105, 1500);
sourceHigh = makeProfile(175, 2100);
target = makeProfile(205, 2450);
target.profileRole = 'target_reference';

config = makeDefaultConfig();
voiceConfig = config.voice;
voiceConfig.enabled = true;
voiceConfig.type = 'female';
voiceConfig.mode = 'female';
voiceConfig.intensity = 0.65;
voiceConfig.params.targetProfile = target;

[lowCfg, lowDiag] = adaptVoiceStyleConfig(sourceLow, voiceConfig);
[highCfg, highDiag] = adaptVoiceStyleConfig(sourceHigh, voiceConfig);

assert(strcmp(lowDiag.targetSource, 'reference_profile'), ...
    'Target reference profile should be used.');
assert(abs(lowDiag.targetF0 - target.f0Median) < 1e-12, ...
    'Target F0 should come from reference profile.');
assert(lowCfg.pitchShift > highCfg.pitchShift, ...
    'Same target profile should adapt differently to different source F0s.');
assert(isfinite(lowCfg.lowGain) && isfinite(lowCfg.highGain), ...
    'Reference-conditioned timbre gains must be finite.');

disp('test_17_reference_profile_adaptation passed: one target profile adapts to different source users.');
